    for name,weight,answer in maps[i]:
        kind,t=lookup[name]
        sid=kind+':'+t['id']
        if sid not in concepts:
            caseids=t.get('caseIds',[])
            if kind=='chapter':
                caseids=[cid for term in catalog['terms'] if term['id'] in t['termIds'] for cid in term['caseIds']]
            cases=[x for x in catalog['cases'] if x['id'] in caseids]
            concepts[sid]={'id':sid,'name':name,'kind':kind,'recordId':t['id'],'cover':t.get('cover',''),'cases':cases,'href':('/terms/'+t['id'].encode().hex()+'/') if kind=='term' else '/#/chapter/'+t['id']}
        edges.append({'styleId':sid,'answer':answer,'weight':weight})
    desires.append({'id':f'D{i:02}','label':label,'line':line,'status':'draft' if i in [1,2,3,11,18] else 'trial','opposite':{17:'D18',18:'D17',22:'D23',23:'D22'}.get(i),'crossNote':{1:'幽玄用遮，Normcore 用混。两条看起来毫无关系的路，回答的是同一个要求。',3:'松弛感是「我本来就不费力」，低能量是「我今天举不起来」。一个是能力，一个是状态。'}.get(i,''),'styles':edges})
